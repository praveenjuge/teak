/**
 * Generates the Android app's string resources from packages/i18n.
 * Regenerate after changing a catalog there:
 *   bun --no-env-file run apps/android/scripts/i18n.ts --write
 */
import { resolve } from "node:path";
import {
  type Locale,
  SUPPORTED_LOCALES,
} from "../../../packages/i18n/src/locales";
import {
  type Arguments,
  loadNativeCatalogs,
  parseNativeMessage,
  position,
  type Segment,
} from "../../../packages/i18n/src/native";

const ANDROID = resolve(import.meta.dir, "..");
const MESSAGES_DIR = resolve(
  import.meta.dir,
  "../../../packages/i18n/messages"
);
const I18N = "core/i18n/src/main";
const HEADER =
  "<!-- Generated by apps/android/scripts/i18n.ts from packages/i18n. Don't edit. -->";

/** The `values-…` folder Android reads a locale from. */
export const resourceQualifier = (locale: Locale): string => {
  if (locale === "en") {
    return "values";
  }
  const [language, region] = locale.split("-");
  if (region === undefined) {
    return `values-${language}`;
  }
  return region.length === 2
    ? `values-${language}-r${region}`
    : `values-b+${language}+${region}`;
};

/** A catalog key as a resource name: `native.library.title` → `native_library_title`. */
export const resourceName = (key: string): string => {
  const name = key.replaceAll(".", "_");
  if (!/^[A-Za-z][A-Za-z0-9_]*$/.test(name)) {
    throw new Error(`${key} can't be an Android resource name`);
  }
  return name;
};

const escapeText = (text: string, hasValues: boolean) =>
  text
    .replaceAll("\\", "\\\\")
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll("'", "\\'")
    .replaceAll('"', '\\"')
    .replaceAll("\n", "\\n")
    .replaceAll("%", hasValues ? "%%" : "%")
    .replace(/^([@?])/, "\\$1");

const formatted = (segments: Segment[], args: Arguments): string => {
  const hasValues = args.count !== undefined || args.names.length > 0;
  return segments
    .map((segment) => {
      if ("text" in segment) {
        return escapeText(segment.text, hasValues);
      }
      const index = position(args, segment);
      return "count" in segment ? `%${index}$d` : `%${index}$s`;
    })
    .join("");
};

const resourceEntry = (key: string, message: string, args: Arguments) => {
  const name = resourceName(key);
  const parsed = parseNativeMessage(message);
  if (parsed.kind === "plain") {
    const text = formatted(parsed.segments, args);
    const plainPercent =
      args.names.length === 0 && !args.count && text.includes("%");
    return `    <string name="${name}"${plainPercent ? ' formatted="false"' : ""}>${text}</string>`;
  }
  const items = Object.entries(parsed.forms).map(
    ([category, segments]) =>
      `        <item quantity="${category}">${formatted(segments, args)}</item>`
  );
  return [`    <plurals name="${name}">`, ...items, "    </plurals>"].join(
    "\n"
  );
};

export const renderAndroidResources = async (): Promise<
  Map<string, string>
> => {
  const { messages, arguments: args } = await loadNativeCatalogs(
    MESSAGES_DIR,
    "android"
  );
  const keys = [...messages.en.keys()].sort();
  const files = new Map<string, string>();
  for (const locale of SUPPORTED_LOCALES) {
    const entries = keys.map((key) =>
      resourceEntry(
        key,
        messages[locale].get(key) ?? (messages.en.get(key) as string),
        args.get(key) as Arguments
      )
    );
    files.set(
      `${I18N}/res/${resourceQualifier(locale)}/strings.xml`,
      [
        '<?xml version="1.0" encoding="utf-8"?>',
        HEADER,
        "<resources>",
        ...entries,
        "</resources>",
        "",
      ].join("\n")
    );
  }

  const plural = (key: string) => args.get(key)?.count !== undefined;
  const mapEntries = (filter: (key: string) => boolean, type: string) =>
    keys
      .filter(filter)
      .map((key) => `        "${key}" to R.${type}.${resourceName(key)},`)
      .join("\n");
  files.set(
    `${I18N}/kotlin/com/praveenjuge/teak/core/i18n/Catalog.kt`,
    `// Generated by apps/android/scripts/i18n.ts from packages/i18n. Don't edit.
package com.praveenjuge.teak.core.i18n

/** Every catalog key the app can read, by its string or plurals resource. */
internal object Catalog {
    val strings: Map<String, Int> = mapOf(
${mapEntries((key) => !plural(key), "string")}
    )

    val plurals: Map<String, Int> = mapOf(
${mapEntries(plural, "plurals")}
    )
}
`
  );

  files.set(
    "app/src/main/res/xml/locales_config.xml",
    [
      '<?xml version="1.0" encoding="utf-8"?>',
      HEADER,
      '<locale-config xmlns:android="http://schemas.android.com/apk/res/android">',
      ...SUPPORTED_LOCALES.map(
        (locale) => `    <locale android:name="${locale}" />`
      ),
      "</locale-config>",
      "",
    ].join("\n")
  );
  return files;
};

if (import.meta.main) {
  const files = await renderAndroidResources();
  for (const [path, contents] of files) {
    if (process.argv.includes("--write")) {
      await Bun.write(resolve(ANDROID, path), contents);
      console.log(`Wrote apps/android/${path}`);
    } else {
      console.log(`apps/android/${path}: ${contents.length} bytes`);
    }
  }
}
