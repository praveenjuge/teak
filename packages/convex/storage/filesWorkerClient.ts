/**
 * Body-bound POST client for internal operations on files.teakvault.com.
 * Contracts are shared through @teak/files-protocol; authentication binds the
 * exact JSON bytes, request id, and short expiration into one HMAC.
 */

import {
  buildFilesOpSigningPayload,
  buildMultipartPartSigningPayload,
  buildUploadSigningPayload,
  FILES_OP_PATH,
  FILES_PROTOCOL_VERSION,
  FILES_UPLOAD_MAX_TTL_SECONDS,
  FILES_UPLOAD_PATH,
  type FilesEnvelope,
  type FilesErrorCode,
  type FilesFinalizeImageResult,
  type FilesOp,
  type FilesOpRequest,
  readFilesAiGenerationFacts,
} from "@teak/files-protocol";
import { env } from "../_generated/server";
import { assertR2KeyInNamespace, hmacSha256Hex } from "./r2Keys";

// Op URLs are minted per action invocation; a short TTL bounds the replay
// window (the worker additionally rejects exps further than 15 min out).
export const FILES_OP_TTL_SECONDS = 10 * 60;

// Ops bounded so a stuck call fails and retries instead of holding the action.
// Rendering and media jobs may include a renderer cold start.
const OP_TIMEOUT_MS: Partial<Record<FilesOp, number>> = {
  "abort-multipart": 90_000,
  "capture-screenshot": 90_000,
  "delete-objects": 90_000,
  "extract-video-frame": 90_000,
  "freeze-object": 90_000,
  "generate-link-metadata": 90_000,
  "generate-text-metadata": 90_000,
  "probe-media": 90_000,
  // One decode, an optional conversion retry, and Whisper on up to 100 MiB.
  "process-audio": 300_000,
  "render-pdf-thumbnail": 90_000,
  "scrape-html": 90_000,
  // Up to six redirect hops of 30 s each in the fetcher, plus a cold start.
  "store-remote-asset": 240_000,
};

export const isFilesWorkerConfigured = (): boolean =>
  Boolean(env.FILES_BASE && env.FILES_SIGNING_SECRET);

export interface SignedUploadUrl {
  expiresAt: number;
  key: string;
  url: string;
}

/**
 * Mint a signed single-file PUT URL on the Files Worker. The signature binds
 * the HTTP method, object key, expiry, content type, and — when known ahead
 * of time — the exact byte size. An empty contentType leaves the content type
 * unbound (the worker stores the request's validated Content-Type); use it
 * when the encoding is decided at generation time.
 */
export const buildSignedWorkerUploadUrl = async (
  {
    contentType,
    key,
    size = null,
    ttlSeconds = 10 * 60,
  }: {
    contentType: string;
    key: string;
    size?: number | null;
    ttlSeconds?: number;
  },
  nowSeconds = Math.floor(Date.now() / 1000)
): Promise<SignedUploadUrl> => {
  const base = env.FILES_BASE;
  const secret = env.FILES_SIGNING_SECRET;
  if (!(base && secret)) {
    throw new Error("files_worker_not_configured");
  }
  if (
    !Number.isSafeInteger(ttlSeconds) ||
    ttlSeconds <= 0 ||
    ttlSeconds > FILES_UPLOAD_MAX_TTL_SECONDS
  ) {
    throw new Error("invalid_upload_ttl");
  }
  assertR2KeyInNamespace(key);
  const expiresAtNumber = nowSeconds + ttlSeconds;
  const expiresAt = String(expiresAtNumber);
  const signature = await hmacSha256Hex(
    secret,
    buildUploadSigningPayload({ contentType, expiresAt, key, size })
  );
  const url = new URL(
    `${base.replace(/\/+$/, "")}${FILES_UPLOAD_PATH}/${encodeURIComponent(key)}`
  );
  if (contentType) {
    url.searchParams.set("ct", contentType);
  }
  url.searchParams.set("exp", expiresAt);
  url.searchParams.set("sig", signature);
  if (size !== null) {
    url.searchParams.set("sz", String(size));
  }
  return { expiresAt: expiresAtNumber, key, url: url.toString() };
};

/**
 * Upload server-generated bytes through the signed single-file endpoint so
 * they never transit Convex storage. Size is unbound because generated media
 * sizes are only known after generation; the worker enforces its own cap.
 */
export const putObjectViaFilesWorker = async ({
  body,
  contentType,
  key,
  signal,
}: {
  body: Blob | ArrayBuffer | Uint8Array;
  contentType: string;
  key: string;
  signal?: AbortSignal;
}): Promise<{ etag: string; key: string; size: number }> => {
  const signed = await buildSignedWorkerUploadUrl({ contentType, key });
  const response = await fetch(signed.url, {
    body: body instanceof Uint8Array ? new Uint8Array(body) : body,
    headers: {
      "content-type": contentType,
      // Content-Length is set automatically for fixed-size bodies.
      "x-teak-request-id": crypto.randomUUID(),
    },
    method: "PUT",
    signal,
  });
  const envelope = (await response.json().catch(() => null)) as FilesEnvelope<{
    etag: string;
    key: string;
    size: number;
  }> | null;
  if (!(response.ok && envelope?.ok)) {
    throw new Error(`files_worker_upload_error:${response.status}`);
  }
  return envelope.data;
};

const sha256Hex = async (value: string): Promise<string> => {
  const digest = await crypto.subtle.digest(
    "SHA-256",
    new TextEncoder().encode(value)
  );
  return Array.from(new Uint8Array(digest), (byte) =>
    byte.toString(16).padStart(2, "0")
  ).join("");
};

