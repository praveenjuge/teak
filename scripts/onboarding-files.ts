/**
 * Embeds the getting-started files (packages/convex/card/onboarding) into
 * packages/convex/card/onboarding/files.ts, so every deployment, self-hosted
 * ones included, can give new accounts their first image, voice memo, PDF,
 * and video without fetching anything at sign-up.
 *
 * Usage: bun run scripts/onboarding-files.ts [--check]
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { extname, join } from "node:path";

const ROOT = join(import.meta.dir, "..");
export const ONBOARDING_DIR = join(ROOT, "packages/convex/card/onboarding");
export const OUTPUT = join(ONBOARDING_DIR, "files.ts");
const EMBEDDED_EXTENSIONS = new Set([
  ".jpg",
  ".m4a",
  ".mp4",
  ".pdf",
  ".png",
  ".webp",
]);

/** The generated module for the files in `dir`, sorted by name. */
export const renderOnboardingFiles = (dir: string): string => {
  const names = readdirSync(dir)
    .filter((name) => EMBEDDED_EXTENSIONS.has(extname(name)))
    .sort();
  const entries = names.map(
    (name) =>
      `  "${name}":\n    "${readFileSync(join(dir, name)).toString("base64")}",`
  );
  return [
    "// Generated by scripts/onboarding-files.ts from the files beside it. Do not edit.",
    "",
    "/** Base64 bytes of each getting-started file, by file name. */",
    "export const ONBOARDING_FILES: Record<string, string> = {",
    ...entries,
    "};",
    "",
  ].join("\n");
};

if (import.meta.main) {
  const rendered = renderOnboardingFiles(ONBOARDING_DIR);
  if (process.argv.includes("--check")) {
    if (readFileSync(OUTPUT, "utf8") !== rendered) {
      console.error(
        "packages/convex/card/onboarding/files.ts is stale: run bun run scripts/onboarding-files.ts"
      );
      process.exit(1);
    }
  } else {
    writeFileSync(OUTPUT, rendered);
  }
}
