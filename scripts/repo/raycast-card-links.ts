/**
 * Raycast can't import the workspace when it ships, so it carries a generated
 * copy of Teak's card link reader: the same rules for which `[[Title|teak:id]]`
 * tokens are links and which sit in code. This lives outside apps/raycast,
 * which is published to the Raycast Store as it is. Regenerate after changing
 * packages/convex/shared/cardLinks.ts:
 *   bun --no-env-file run scripts/repo/raycast-card-links.ts --write
 */
import { resolve } from "node:path";
import { format } from "prettier";

export const CARD_LINKS_SOURCE_PATH = resolve(
  import.meta.dir,
  "../../packages/convex/shared/cardLinks.ts"
);

export const TEAK_CARD_LINKS_PATH = resolve(
  import.meta.dir,
  "../../apps/raycast/src/lib/teakCardLinks.ts"
);

const HEADER = [
  "// Generated by scripts/repo/raycast-card-links.ts from",
  "// packages/convex/shared/cardLinks.ts. Don't edit.",
  "",
].join("\n");

/** Raycast's `ray lint` checks Prettier's formatting, with its defaults. */
export const renderTeakCardLinks = async (): Promise<string> =>
  format(`${HEADER}${await Bun.file(CARD_LINKS_SOURCE_PATH).text()}`, {
    parser: "typescript",
  });

if (import.meta.main) {
  if (process.argv.includes("--write")) {
    await Bun.write(TEAK_CARD_LINKS_PATH, await renderTeakCardLinks());
    console.log(`Wrote ${TEAK_CARD_LINKS_PATH}`);
  } else {
    process.stdout.write(await renderTeakCardLinks());
  }
}
